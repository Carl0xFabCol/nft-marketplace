#!/usr/bin/env node
// gen-types-local.mjs: regenerate the ONE canonical Supabase types file,
// apps/web/lib/supabase/types.ts, from a LOCAL database only.
//
//   pnpm --filter @marketplace/database gen:types:local -- --workdir <dir holding supabase/>
//   pnpm --filter @marketplace/database gen:types:local -- --db-url postgresql://postgres:postgres@127.0.0.1:54322/postgres
//   … add --check to fail (exit 1) when the committed file differs instead of writing it.
//
// The local database must hold the committed baseline + every migration in
// packages/database/migrations (see docs/PHASE3B_RUNBOOK.md for the rehearsal
// stack). Remote projects are refused on purpose: types come from the schema
// in this repository, never from whatever a hosted project currently has.
// No .env is read.
import { execFileSync, execSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const pkgRoot = path.resolve(here, "..")
const OUT = path.resolve(pkgRoot, "../../apps/web/lib/supabase/types.ts")
const PRETTIER = "prettier@3.3.3"
const LOCAL_HOSTS = new Set(["127.0.0.1", "localhost", "::1", "[::1]"])

function arg(name) {
  const i = process.argv.indexOf(name)
  return i >= 0 ? process.argv[i + 1] : undefined
}

export function assertLocalDbUrl(url) {
  let host
  try {
    host = new URL(url).hostname
  } catch {
    throw new Error(`Invalid --db-url`)
  }
  if (!LOCAL_HOSTS.has(host)) throw new Error(`Refusing non-local database host "${host}": types are generated from a local stack only.`)
  return url
}

const HEADER = `// ─────────────────────────────────────────────────────────────────────────────
// AUTO-GENERATED by packages/database/scripts/gen-types-local.mjs. DO NOT EDIT.
// Source: a LOCAL database with the committed baseline + packages/database/
// migrations applied (never a hosted project). Regenerate:
//   pnpm --filter @marketplace/database gen:types:local -- --workdir <local supabase project>
// This is the single canonical Supabase types file of the monorepo.
// ─────────────────────────────────────────────────────────────────────────────

`

function run(cmd, args, input) {
  const opts = { cwd: pkgRoot, encoding: "utf8", input, stdio: [input === undefined ? "ignore" : "pipe", "pipe", "inherit"], maxBuffer: 64 * 1024 * 1024 }
  if (process.platform !== "win32") return execFileSync(cmd, args, opts)
  // Windows: npx is a .cmd shim and needs a shell; quote every argument ourselves.
  const quoted = [cmd, ...args].map((a) => (/^[\w@./:=-]+$/.test(a) ? a : `"${a.replace(/"/g, '\\"')}"`)).join(" ")
  return execSync(quoted, opts)
}

function main() {
  const workdir = arg("--workdir")
  const dbUrl = arg("--db-url")
  if (!workdir === !dbUrl) throw new Error("Pass exactly one of --workdir <local project dir> or --db-url <local url>.")

  const source = workdir
    ? ["--local", "--workdir", path.resolve(workdir)]
    : ["--db-url", assertLocalDbUrl(dbUrl)]
  const raw = run("npx", ["supabase", "gen", "types", "typescript", ...source, "--schema", "public"])
  if (!raw.includes("export type Database")) throw new Error("supabase gen types produced no Database type")

  const formatted = run("npx", ["--yes", PRETTIER, "--parser", "typescript", "--print-width", "120", "--no-semi"], raw)
  const next = (HEADER + formatted).replace(/\r\n/g, "\n")

  if (process.argv.includes("--check")) {
    const current = readFileSync(OUT, "utf8").replace(/\r\n/g, "\n")
    if (current !== next) {
      console.error(`${path.relative(process.cwd(), OUT)} is out of date with the local schema. Regenerate it.`)
      process.exit(1)
    }
    console.log("types.ts is up to date")
    return
  }
  writeFileSync(OUT, next)
  console.log(`wrote ${path.relative(process.cwd(), OUT)}`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main()
  } catch (e) {
    console.error(e instanceof Error ? e.message : e)
    process.exit(1)
  }
}
